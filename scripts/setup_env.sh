#!/usr/bin/env bash
# Build the project environment reproducibly.
#
#   bash scripts/setup_env.sh              # create .venv and install everything
#   bash scripts/setup_env.sh --recreate   # delete .venv first
#   bash scripts/setup_env.sh --lock       # also refresh requirements.lock.txt
#   bash scripts/setup_env.sh --no-test    # skip the environment test run
#
# Why Python 3.10: the upstream submodule pins torch==1.12.1, which publishes
# no wheels for Python 3.11+. See docs/setup.md.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

PY_VERSION="$(tr -d '[:space:]' < .python-version)"
VENV="$REPO_ROOT/.venv"
PIP_VERSION="24.2"

RECREATE=0; LOCK=0; RUN_TESTS=1
for arg in "$@"; do
  case "$arg" in
    --recreate) RECREATE=1 ;;
    --lock)     LOCK=1 ;;
    --no-test)  RUN_TESTS=0 ;;
    -h|--help)  sed -n '2,10p' "$0"; exit 0 ;;
    *) echo "unknown flag: $arg" >&2; exit 2 ;;
  esac
done

echo "==> repository: $REPO_ROOT"
echo "==> target python: $PY_VERSION"

# --- 1. submodules --------------------------------------------------------- #
if [ ! -f "neural-astar/pyproject.toml" ] || [ ! -f "neural-astar/planning-datasets/data/mpd/mazes_032_moore_c8.npz" ]; then
  echo "==> fetching submodules (neural-astar + nested planning-datasets)"
  git submodule update --init --recursive
fi
if [ ! -e "data/mazes_032_moore_c8.npz" ]; then
  echo "==> linking data/mazes_032_moore_c8.npz"
  mkdir -p data
  ln -sf ../neural-astar/planning-datasets/data/mpd/mazes_032_moore_c8.npz \
         data/mazes_032_moore_c8.npz
fi

# --- 2. interpreter -------------------------------------------------------- #
PYTHON_BIN=""
if command -v pyenv >/dev/null 2>&1; then
  if [ ! -x "$(pyenv root)/versions/$PY_VERSION/bin/python" ]; then
    echo "==> pyenv install $PY_VERSION (compiles from source, a few minutes)"
    pyenv install -s "$PY_VERSION"
  fi
  PYTHON_BIN="$(pyenv root)/versions/$PY_VERSION/bin/python"
elif command -v "python${PY_VERSION%.*}" >/dev/null 2>&1; then
  PYTHON_BIN="$(command -v "python${PY_VERSION%.*}")"
else
  echo "ERROR: need Python ${PY_VERSION%.*} (pyenv recommended). See docs/setup.md." >&2
  exit 1
fi
echo "==> interpreter: $PYTHON_BIN ($("$PYTHON_BIN" -V 2>&1))"

# --- 3. virtualenv --------------------------------------------------------- #
if [ "$RECREATE" = "1" ] && [ -d "$VENV" ]; then
  echo "==> removing existing $VENV"
  rm -rf "$VENV"
fi
if [ ! -d "$VENV" ]; then
  echo "==> creating $VENV"
  "$PYTHON_BIN" -m venv "$VENV"
fi

# --- 4. dependencies ------------------------------------------------------- #
# One pip invocation for both dependency sets, so the resolver sees upstream's
# pins and ours at the same time (numpy in particular: upstream accepts 2.x,
# which is ABI-incompatible with torch 1.12.1).
echo "==> installing dependencies"
"$VENV/bin/pip" install -q "pip==$PIP_VERSION"
"$VENV/bin/pip" install -q -e "./neural-astar[dev]" -r requirements.txt

# --- 5. lockfile ----------------------------------------------------------- #
if [ "$LOCK" = "1" ]; then
  echo "==> refreshing requirements.lock.txt"
  {
    echo "# Generated by scripts/setup_env.sh --lock -- do not edit by hand."
    echo "# Python $("$VENV/bin/python" -V 2>&1 | cut -d' ' -f2) on $(uname -s)/$(uname -m)."
    echo "# Install with: pip install -r requirements.lock.txt (after pip install -e ./neural-astar --no-deps)"
    # --all keeps setuptools/wheel in the lock: setuptools is a *runtime*
    # dependency here, because pytorch_lightning 1.8.5 imports pkg_resources.
    "$VENV/bin/pip" freeze --exclude-editable --all | grep -Ev "^(pip|distribute)=="
  } > requirements.lock.txt
fi

# --- 6. verify ------------------------------------------------------------- #
if [ "$RUN_TESTS" = "1" ]; then
  echo "==> verifying the environment"
  "$VENV/bin/python" -m pytest tests/test_env.py
fi

echo
echo "Done. Activate with:  source .venv/bin/activate"
